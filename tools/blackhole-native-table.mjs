// blackhole-native-table.mjs — the black hole's QNM table (blackhole/data/qnm-table.json, made by
// tools/qnm-table.mjs) as a C++ header for its native port: the same numbers, converted, not
// solved again.
//
// Usage: node tools/blackhole-native-table.mjs           writes native/instruments/blackhole/qnm-table.h
//        node tools/blackhole-native-table.mjs --check   exit 1 if that file is stale

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

export const headerFile = new URL('../native/instruments/blackhole/qnm-table.h', import.meta.url);
const tableFile = new URL('../blackhole/data/qnm-table.json', import.meta.url);
const num = (v) => { const s = String(v); return /[.e]/.test(s) ? s : `${s}.0`; }; // every value as JavaScript prints it
const list = (a) => a.map(num).join(', ');

export function header(TABLE = JSON.parse(readFileSync(tableFile, 'utf8'))) {
  const NU = TABLE.u.length;
  for (const md of TABLE.modes) if (md.re.length !== NU || md.im.length !== NU) throw new Error(`(${md.l},${md.m},${md.n}): not one value per spin`);
  const out = [
    '// qnm-table.h — generated by tools/blackhole-native-table.mjs from blackhole/data/qnm-table.json',
    '// (made by tools/qnm-table.mjs). Do not edit; after changing the table, run',
    '//   node tools/blackhole-native-table.mjs',
    '//',
    `// ${TABLE.note}`,
    '#pragma once',
    '',
    'namespace forte::blackhole::table {',
    '',
    `constexpr int NU = ${NU};          // spins, in u = −log10(1 − a)`,
    `constexpr int NMODES = ${TABLE.modes.length};      // (l, m, n)`,
    '',
    'struct Mode { int l, m, n; double re[NU], im[NU]; }; // Re Mω and Im Mω at each u',
    '',
    `inline constexpr double kU[NU] = {${list(TABLE.u)}};`,
    '',
    'inline constexpr Mode kModes[NMODES] = {',
  ];
  for (const md of TABLE.modes) out.push(`  {${md.l}, ${md.m}, ${md.n}, {${list(md.re)}},`, `   {${list(md.im)}}},`);
  out.push('};', '', '} // namespace forte::blackhole::table', '');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = header();
  if (process.argv.includes('--check')) {
    if (!existsSync(headerFile) || readFileSync(headerFile, 'utf8') !== text) { console.error('native/instruments/blackhole/qnm-table.h is stale: run node tools/blackhole-native-table.mjs'); process.exit(1); }
    console.log('native/instruments/blackhole/qnm-table.h is fresh');
  } else {
    writeFileSync(headerFile, text);
    console.log('native/instruments/blackhole/qnm-table.h');
  }
}

// Tune the Pipe Organ's pipes in the engine: blow each pipe alone at the default wind and voicing
// (48 kHz), measure how far it sounds from the frequency the linear analysis promised, and write the
// correction as a function of frequency to pipes/src/tuning-table.js, as a voicer tunes a pipe by
// cutting it. Three passes, starting from the table already there. It also writes the C++ port's
// copy, native/instruments/pipes/tuning-table.h. The engine and the model are the C++ (built as
// WebAssembly); each pass hands the model the correction it is trying, so no rebuild is needed
// until the end: then rebuild (native/README.md), and --check measures the build.
// Usage: node tools/pipes-tuning.mjs            (→ pipes/src/tuning-table.js and its C++ copy, a few minutes)
//        node tools/pipes-tuning.mjs --extend   (the same, but only for rows no pipe of the compass (C–f³) reads:
//                                                they keep their tuning to the last bit, the pipes past it get theirs)
//        node tools/pipes-tuning.mjs --check    (only measures every pipe the organ has, as built: exit 1 if one is 0.4 ¢ off or more)
//        node tools/pipes-tuning.mjs --native   (only the C++ copy, from the JavaScript table as it is)

import { writeFileSync } from 'node:fs';
import { INSTRUMENT, DEFAULTS } from '../pipes/src/pipes-instrument.js';
import { KEY_LO, KEY_HI, KEY_MIN, KEY_MAX, RANKS, organName } from '../pipes/src/pipes-data.js';
import { TUNING } from '../pipes/src/tuning-table.js';
import { wasmModel } from '../pipes/src/pipes-wasm.js';
import { loadEngine } from './engine.mjs';

const FS = 48000, TAU = 2 * Math.PI;
const OS_FREQ = 2000, F_MAX = 15000; // Hz: pipes-engine.h's fOS (pipes from here up run at 2×, from 3× it at 4×) and pipes-model.h's F_MAX

// The C++ port's copy of the table (the same numbers, so the same doubles).
export const tuningHeader = (T) => `// tuning-table.h — generated by tools/pipes-tuning.mjs from pipes/src/tuning-table.js; do not edit.
// How far each pipe sounds from what the linear analysis predicts, measured in the engine at the
// default wind and voicing (48 kHz). The model multiplies the pipe's resonance by \`tune\` so that
// it sounds its note. Rows: {log2 f, tune}.
#pragma once

namespace forte::pipes {

struct TuneRow { double x, tune; };
inline constexpr TuneRow TUNING_OPEN[] = {
${T.open.map((r) => `  {${r.join(', ')}},`).join('\n')}
};
inline constexpr TuneRow TUNING_STOPPED[] = {
${T.stopped.map((r) => `  {${r.join(', ')}},`).join('\n')}
};

} // namespace forte::pipes
`;
const HEADER = new URL('../native/instruments/pipes/tuning-table.h', import.meta.url);
let PipeEngine, M; // loaded when run, not when the tests import tuningHeader

// sounding frequency of x near f over [a, b): phase advance of the demodulated signal, over 64
// samples (unambiguous within ±375 Hz), then 512, then the whole span; the window at least four
// periods (2048 samples down to 94 Hz)
function freqAt(x, f, a, b) {
  const m = Math.max(2048, Math.ceil((4 * FS) / f)), ph = (s, fr) => { const w = (TAU * fr) / FS; let re = 0, im = 0; for (let i = s; i < s + m; i++) { const h = 0.5 - 0.5 * Math.cos((TAU * (i - s)) / m); re += h * x[i] * Math.cos(w * i); im -= h * x[i] * Math.sin(w * i); } return Math.atan2(im, re); };
  const wrap = (d) => d - TAU * Math.round(d / TAU);
  let fr = f;
  for (const lag of [64, 512, b - m - a]) fr += (wrap(ph(a + lag, fr) - ph(a, fr)) * FS) / (TAU * lag);
  return fr;
}
// One pipe sounding f, cut with the correction `tune`, alone, on the Principal's slot of a key (the
// engine's models for that key are replaced by this one pipe). Below 60 Hz the pipes speak slowly
// (2 s at A₂): measured later.
function measure(f, stopped, tune) {
  const dur = f < 60 ? 1.6 + 3 * (60 / f - 1) : 1.6;
  const e = new PipeEngine(FS);
  const P = { ...DEFAULTS, principal: true, octave: false, gedackt: false, mixture: false, noise: 0 };
  e.setParams(P);
  const R = M.pipeModel(f, stopped, P, { tune });
  e.modelsFor = () => [R, R, R, R, R, R];
  e.noteOn(60, 0.7);
  const n = Math.round(dur * FS), L = new Float64Array(n), bL = new Float32Array(128), bR = new Float32Array(128);
  for (let s = 0; s < n; s += 128) { e.process(bL, bR, 128); for (let i = 0; i < 128 && s + i < n; i++) L[s + i] = bL[i]; }
  e.destroy();
  return freqAt(L, f, Math.round((dur - 0.7) * FS), n);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--native')) {
    writeFileSync(HEADER, tuningHeader(TUNING.table));
    console.log('native/instruments/pipes/tuning-table.h');
    process.exit(0);
  }
  PipeEngine = await loadEngine(INSTRUMENT);
  M = await wasmModel();
  if (process.argv.includes('--check')) { // every pipe as the build cuts it (its own table): the compass's within 0.4 ¢, the full range's within 2 ¢
    const worst = [{ c: 0, at: '' }, { c: 0, at: '' }];
    for (let k = KEY_MIN; k <= KEY_MAX; k++) for (let r = 0; r < RANKS.length; r++) {
      const f = M.pipeFreq(k, r), st = RANKS[r].stopped, c = 1200 * Math.log2(measure(f, st, M.tuning(f, st)) / f);
      const w = worst[k >= KEY_LO && k <= KEY_HI ? 0 : 1];
      if (Math.abs(c) > Math.abs(w.c)) { w.c = c; w.at = `${organName(k)} ${RANKS[r].id}`; }
    }
    console.log(`worst ${worst[0].c.toFixed(3)} ¢ (${worst[0].at}) on the compass, ${worst[1].c.toFixed(3)} ¢ (${worst[1].at}) past it`);
    process.exit(Math.abs(worst[0].c) < 0.4 && Math.abs(worst[1].c) < 2 ? 0 : 1);
  }
  // every pipe of A₂–c⁵ (the full range) is on or between the grid's points
  const pipes = { open: [], stopped: [] }, compass = { open: [], stopped: [] };
  for (let k = KEY_MIN; k <= KEY_MAX; k++) for (let r = 0; r < RANKS.length; r++) {
    const kind = RANKS[r].stopped ? 'stopped' : 'open', x = Math.log2(M.pipeFreq(k, r));
    pipes[kind].push(x);
    if (k >= KEY_LO && k <= KEY_HI) compass[kind].push(x);
  }
  const grid = { open: [], stopped: [] };
  for (const kind of ['open', 'stopped']) {
    const lo = 2 ** Math.min(...pipes[kind]) * 0.98, hi = 2 ** Math.max(...pipes[kind]) * 1.02;
    // sixths of an octave from 60 Hz, up and down
    for (let k = Math.floor(6 * Math.log2(lo / 60)); 60 * 2 ** (k / 6) <= hi; k++) grid[kind].push(Math.log2(60) + k / 6);
    // steps in the model: from OS_FREQ up the engine runs a pipe at twice the rate, from 3 × OS_FREQ
    // at four times, and a mode drops out where it would pass F_MAX: tune both sides of each step
    const steps = [OS_FREQ, 3 * OS_FREQ];
    for (let n = 1; n <= 12; n++) steps.push(F_MAX / (kind === 'stopped' ? 2 * n - 1 : n));
    for (const fb of steps) if (fb > lo && fb < hi) grid[kind].push(Math.log2(fb) - 1e-4, Math.log2(fb) + 1e-4);
    // and above 2 kHz, where the tuning bends between the steps, and below 60 Hz, every pipe the organ has
    for (const x of pipes[kind]) if (2 ** x > 2000 || 2 ** x < 60) grid[kind].push(x);
    grid[kind] = [...new Set(grid[kind].map((x) => +x.toFixed(6)))].sort((a, b) => a - b);
  }
  // --extend: the rows a pipe of the compass reads (the two either side of it, or the end row it is
  // past) stay as they are, and no row goes between them; a pipe past an end row is pinned to that
  // row's tuning by a row of the same tuning just beyond it
  const fixed = { open: [], stopped: [] };
  if (process.argv.includes('--extend')) {
    for (const kind of ['open', 'stopped']) {
      const t = TUNING.table[kind], keep = new Set(), spans = [];
      for (const x of compass[kind]) {
        if (x <= t[0][0]) { keep.add(0); spans.push([x, t[0][0]]); continue; }
        if (x > t[t.length - 1][0]) { keep.add(t.length - 1); spans.push([t[t.length - 1][0], x]); continue; }
        const i = t.findIndex((r) => x <= r[0]);
        keep.add(i - 1); keep.add(i); spans.push([t[i - 1][0], t[i][0]]);
      }
      fixed[kind] = [...keep].sort((a, b) => a - b).map((i) => t[i]);
      const last = t[t.length - 1], past = compass[kind].filter((x) => x > last[0]), first = t[0], below = compass[kind].filter((x) => x < first[0]);
      if (past.length) { const x = Math.ceil(Math.max(...past) * 1e6) / 1e6; fixed[kind].push([x, last[1]]); spans.push([last[0], x]); }
      if (below.length) { const x = Math.floor(Math.min(...below) * 1e6) / 1e6; fixed[kind].unshift([x, first[1]]); spans.push([x, first[0]]); }
      const lo = Math.min(...spans.map((s) => s[0])), hi = Math.max(...spans.map((s) => s[1]));
      grid[kind] = grid[kind].filter((x) => (x < lo || x > hi) && !fixed[kind].some((r) => r[0] === x));
      console.log(`${kind}: ${fixed[kind].length} rows kept (${lo.toFixed(6)}…${hi.toFixed(6)}), ${grid[kind].length} to measure`);
    }
  }
  const before = (kind) => compass[kind].map((x) => TUNING.lookup(2 ** x, kind === 'stopped'));
  const was = { open: before('open'), stopped: before('stopped') };
  const merge = (kind, rows) => [...fixed[kind], ...rows].sort((a, b) => a[0] - b[0]);
  TUNING.table.open = merge('open', grid.open.map((x) => [x, TUNING.lookup(2 ** x, false)]));
  TUNING.table.stopped = merge('stopped', grid.stopped.map((x) => [x, TUNING.lookup(2 ** x, true)]));
  for (let pass = 0; pass < 3; pass++) {
    const next = { open: [], stopped: [] };
    for (const kind of ['open', 'stopped']) {
      for (const x of grid[kind]) {
        const f = 2 ** x, fm = measure(f, kind === 'stopped', TUNING.lookup(f, kind === 'stopped'));
        const t = TUNING.lookup(f, kind === 'stopped') * (f / fm);
        next[kind].push([+x.toFixed(6), +t.toFixed(7)]);
        if (pass === 2) console.log(kind, f.toFixed(1), 'Hz', (1200 * Math.log2(fm / f)).toFixed(2), '¢ before this pass, tune', t.toFixed(5));
      }
    }
    TUNING.table.open = merge('open', next.open); TUNING.table.stopped = merge('stopped', next.stopped);
  }
  if (process.argv.includes('--extend')) for (const kind of ['open', 'stopped']) {
    const now = before(kind);
    compass[kind].forEach((x, i) => { if (now[i] !== was[kind][i]) throw new Error(`${kind} ${(2 ** x).toFixed(2)} Hz: tune ${was[kind][i]} → ${now[i]}`); });
  }
  const body = `// tuning-table.js — how far each pipe sounds from what the linear analysis predicts, measured in the
// engine at the default wind and voicing (48 kHz) by tools/pipes-tuning.mjs, which writes this file.
// The model multiplies the pipe's resonance by \`tune\` so that it sounds its note. Rows: [log2 f, tune].
const T = {
  open: ${JSON.stringify(TUNING.table.open)},
  stopped: ${JSON.stringify(TUNING.table.stopped)},
};
export const TUNING = {
  table: T,
  lookup(f, stopped) {
    const t = stopped ? T.stopped : T.open;
    if (!t.length) return 1;
    const x = Math.log2(f);
    if (x <= t[0][0]) return t[0][1];
    for (let i = 1; i < t.length; i++) if (x <= t[i][0]) { const [x0, y0] = t[i - 1], [x1, y1] = t[i]; return y0 + ((y1 - y0) * (x - x0)) / (x1 - x0); }
    return t[t.length - 1][1];
  },
};
`;
  writeFileSync(new URL('../pipes/src/tuning-table.js', import.meta.url), body);
  writeFileSync(HEADER, tuningHeader(TUNING.table));
  console.log('wrote pipes/src/tuning-table.js and native/instruments/pipes/tuning-table.h: rebuild, then --check');
}

// Shape every marimba and xylophone bar's undercut and write the table the instrument plays
// from: the marimba's first three bending modes at 1 : 4 : 10, the xylophone's first two at 1 : 3.
// Usage: node tools/marimba-bars.mjs     (→ native/instruments/marimba/marimba-bars.h; then rebuild
//                                         the WebAssembly: cmake --build --preset wasm)
//
// Every key A0–C8 gets a bar of each kind, its blank (width, thickness, the flat share of the cut)
// graded along the real compass (marimba-model.h barBlank) and held past it. The tuning is the C++
// model's (tuneBar, built as WebAssembly): Newton's method from the neighbouring key's answer,
// walking out from the bottom of each compass.

import { writeFileSync } from 'node:fs';
import { wasmModel } from '../marimba/src/marimba-wasm.js';
import { COMPASS, KEY_MIN, KEY_MAX } from '../marimba/src/marimba-instrument.js';

const M = await wasmModel();
// where each kind's walk starts: the bottom of its compass, from a rough guess
const START = { marimba: { A: 0.77, D: 0.65, L: 0.74 }, xylophone: { A: 0.6, D: 0.23, L: 0.47 } };
const rows = {}, worst = {};
for (const kind of ['marimba', 'xylophone']) {
  const lo = COMPASS[kind][0], out = new Map();
  let at = M.tune(kind, lo, START[kind]);
  out.set(lo, at);
  for (const dir of [1, -1]) {
    let prev = at;
    for (let k = lo + dir; k >= KEY_MIN && k <= KEY_MAX; k += dir) {
      const t = M.tune(kind, k, prev);
      out.set(k, t);
      prev = t;
    }
  }
  rows[kind] = [];
  worst[kind] = 0;
  for (let k = KEY_MIN; k <= KEY_MAX; k++) {
    const t = out.get(k);
    worst[kind] = Math.max(worst[kind], ...t.cents.map(Math.abs));
    rows[kind].push(`    {${+t.L.toPrecision(10)}, ${+t.A.toPrecision(10)}, ${+t.D.toPrecision(10)}},`);
  }
  console.log(`${kind}: worst residual ${worst[kind].toExponential(2)} ¢; ${(100 * out.get(KEY_MIN).L).toFixed(1)} cm at A0, ${(100 * out.get(lo).L).toFixed(1)} cm at the compass's bottom, ${(100 * out.get(KEY_MAX).L).toFixed(1)} cm at C8`);
  if (worst[kind] > 0.01) { console.error(`${kind}: a bar did not tune`); process.exit(1); }
}
const header = `// marimba-bars.h — generated by tools/marimba-bars.mjs; do not edit.
// The tuned bars, A0–C8, of the marimba (1 : 4 : 10) and the xylophone (1 : 3): {length L (m),
// the cut's length a/(L/2), its depth d/h₀}. The thickness h₀, the width b and c/a come from
// barBlank(kind, key) in marimba-model.h.
#pragma once

namespace forte::marimba {

struct BarRow { double L, A, D; };
inline constexpr int BAR_COUNT = ${KEY_MAX - KEY_MIN + 1};
inline constexpr BarRow BAR_TABLE[2][BAR_COUNT] = {
  {
${rows.marimba.join('\n')}
  },
  {
${rows.xylophone.join('\n')}
  },
};

} // namespace forte::marimba
`;
writeFileSync(new URL('../native/instruments/marimba/marimba-bars.h', import.meta.url), header);
console.log('native/instruments/marimba/marimba-bars.h');

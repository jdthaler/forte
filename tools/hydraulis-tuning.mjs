// Tune the Hydraulis's pipes in the engine: blow each pipe the instrument has alone, on a still
// wind at the full 700 Pa (48 kHz), measure how far it sounds from the frequency the linear
// analysis promised, and write the correction to native/instruments/hydraulis/hydraulis-tuning.h,
// as a voicer tunes a pipe by cutting it. Nine passes, starting from the table already there, and
// each pipe keeps the cut that came closest; each hands the model the correction it is trying, so
// no rebuild is needed until the end: then rebuild (native/README.md), and --check measures the build. The rows are the pipes' own frequencies (in
// equal temperament at A = 440 Hz), so every pipe is tuned exactly there and a retuned one between.
// Usage: node tools/hydraulis-tuning.mjs            (→ the header, a minute or two)
//        node tools/hydraulis-tuning.mjs --check    (only measures every pipe, as built: exit 1 if one of the compass's is 0.5 ¢ off or more, or one past it 2 ¢)

import { writeFileSync } from 'node:fs';
import { INSTRUMENT, DEFAULTS, KEY_LO, KEY_HI, KEY_MIN, KEY_MAX } from '../hydraulis/src/hydraulis-instrument.js';
import { wasmModel } from '../hydraulis/src/hydraulis-wasm.js';
import { freqAt } from './pipes-tuning.mjs';
import { loadEngine } from './engine.mjs';

const FS = 48000, PASSES = 9, RANKS = [false, true, true, true]; // stopped?
const HEADER = new URL('../native/instruments/hydraulis/hydraulis-tuning.h', import.meta.url);
const Engine = await loadEngine(INSTRUMENT), M = await wasmModel();

// One pipe sounding f, cut with the correction `tune`, alone on a still wind (the bass, slow to speak, longer).
function measure(f, stopped, tune) {
  const dur = f < 80 ? 1.6 + 3 * (80 / f - 1) : 1.6;
  const e = new Engine(FS, 1, { still: true });
  e.setParams({ ...DEFAULTS, open: true, stopped: false, low: false, high: false, noise: 0, fullRange: true });
  const packed = M.pipePacked(f, stopped, DEFAULTS, tune);
  e.modelsFor = () => packed;
  e.noteOn(60, 0.7);
  const n = Math.round(dur * FS), L = new Float64Array(n), bL = new Float32Array(128), bR = new Float32Array(128);
  for (let s = 0; s < n; s += 128) { e.process(bL, bR, 128); for (let i = 0; i < 128 && s + i < n; i++) L[s + i] = bL[i]; }
  e.destroy();
  return freqAt(L, f, Math.round((dur - 0.7) * FS), n);
}

if (process.argv.includes('--check')) {
  const worst = [{ c: 0, at: '' }, { c: 0, at: '' }];
  for (let k = KEY_MIN; k <= KEY_MAX; k++) for (let r = 0; r < 4; r++) {
    const f = M.pipeFreq(k, r), st = RANKS[r], c = 1200 * Math.log2(measure(f, st, M.tuning(f, st)) / f);
    const w = worst[k >= KEY_LO && k <= KEY_HI ? 0 : 1];
    if (Math.abs(c) > Math.abs(w.c)) { w.c = c; w.at = `key ${k} rank ${r}`; }
  }
  console.log(`worst ${worst[0].c.toFixed(3)} ¢ (${worst[0].at}) on the compass, ${worst[1].c.toFixed(3)} ¢ (${worst[1].at}) past it`);
  process.exit(Math.abs(worst[0].c) < 0.5 && Math.abs(worst[1].c) < 2 ? 0 : 1);
}

const rows = { open: new Set(), stopped: new Set() };
for (let k = KEY_MIN; k <= KEY_MAX; k++) for (let r = 0; r < 4; r++) rows[RANKS[r] ? 'stopped' : 'open'].add(+Math.log2(M.pipeFreq(k, r)).toFixed(9));
const T = { open: [...rows.open].sort((a, b) => a - b).map((x) => [x, 1]), stopped: [...rows.stopped].sort((a, b) => a - b).map((x) => [x, 1]) };
for (const kind of ['open', 'stopped']) for (const row of T[kind]) row[1] = M.tuning(2 ** row[0], kind === 'stopped'); // from the table there
for (let pass = 0; pass < PASSES; pass++) {
  let worst = 0, at = '';
  for (const kind of ['open', 'stopped']) for (const row of T[kind]) {
    const f = 2 ** row[0], fm = measure(f, kind === 'stopped', row[1]);
    const c = Math.abs(1200 * Math.log2(fm / f));
    if (c > worst) { worst = c; at = `${kind} ${f.toFixed(1)} Hz`; }
    if (!(c >= row[3])) { row[2] = row[1]; row[3] = c; } // the best cut yet
    row[1] = +(row[1] * (f / fm) ** (pass < 3 ? 1 : 0.6)).toFixed(10); // (later passes step part way: the top pipes' pitch is touchy)
  }
  console.log(`pass ${pass + 1}: worst ${worst.toFixed(2)} ¢ before it (${at})`);
}
for (const kind of ['open', 'stopped']) for (const row of T[kind]) row.splice(1, 3, row[2]); // each pipe keeps its best cut
writeFileSync(HEADER, `// hydraulis-tuning.h — generated by tools/hydraulis-tuning.mjs; do not edit.
// How far each pipe sounds from what the linear analysis predicts, measured in the engine on a
// still wind at the full 700 Pa and the default voicing (48 kHz). The model multiplies the pipe's
// resonance by \`tune\` so that it sounds its note. Rows: {log2 f, tune}, at every pipe the
// instrument has in equal temperament at A = 440 Hz.
#pragma once

namespace forte::hydraulis {

struct TuneRow { double x, tune; };
inline constexpr TuneRow TUNING_OPEN[] = {
${T.open.map((r) => `  {${r.join(', ')}},`).join('\n')}
};
inline constexpr TuneRow TUNING_STOPPED[] = {
${T.stopped.map((r) => `  {${r.join(', ')}},`).join('\n')}
};

} // namespace forte::hydraulis
`);
console.log('wrote native/instruments/hydraulis/hydraulis-tuning.h: rebuild, then --check');

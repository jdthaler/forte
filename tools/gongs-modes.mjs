// Precompute the circular-plate tables for the gong keyboard.
// Usage: node tools/gongs-modes.mjs   → gongs/data/gong-modes.js   (~2 s)
//
// For each edge condition (free, clamped) and ν = 0.33:
//   modes   transverse modes (cos mθ family) with λ² ≤ LAM2, radial shapes
//           sampled on r = 0, 1/64, …, 1 (normalised: ∫_disc Φ² dA = 1);
//   inplane Airy-function modes (clamped-plate modes, the in-plane edge is free),
//           ζ² ≤ ZETA2;
//   H       von Kármán couplings ∫ Ψ_n L(Φ_p, Φ_q) dA, p ≤ q, the strongest ones
//           (by the equipartition weight √C_n |H| / (λ_p² λ_q²)) up to KEEP;
//   E       ∫ Ψ_n ∇²Φ_p dA for those in-plane modes (× κ = a²/(R h) at run time);
//   Kc      the shallow-shell membrane stiffness per κ²,
//           12(1−ν²) Σ_n E_np E_nq / ζ_n⁴, summed over a much larger in-plane basis
//           (ζ² ≤ ZETA2_KC) so that the shell's linear frequencies are converged.
// It is written as an ES module, for the tests; tools/gongs-native-table.mjs converts it to C++
// (native/instruments/gongs/gong-modes.h), which the engine and model use.

import { writeFileSync, mkdirSync } from 'node:fs';
import { plateModes, couplings, radial } from '../gongs/src/plate.js';

const NU = 0.33, NR = 65, ZETA2 = 600, ZETA2_KC = 3000, KEEP = 4000;
const LAM2 = { free: 260, clamped: 320 };
const f6 = (v) => +v.toPrecision(6);

const out = { note: 'Circular plate modes and von Kármán couplings (gongs/src/plate.js, tools/gongs-modes.mjs). Lengths in units of the radius, ∫Φ² dA = 1.', nu: NU, nr: NR };
const t0 = performance.now();
for (const bc of ['free', 'clamped']) {
  const T = plateModes(bc, { nu: NU, lam2Max: LAM2[bc] });
  const mMax = Math.max(...T.map((m) => m.m));
  const P = plateModes('clamped', { lam2Max: ZETA2, mMax: 2 * mMax });
  const { H } = couplings(T, P);
  const C = P.map((p) => (3 * (1 - NU * NU)) / p.lam2 ** 2);
  const w = (h) => (Math.sqrt(C[h.n]) * Math.abs(h.v)) / (T[h.p].lam2 * T[h.q].lam2);
  const kept = H.slice().sort((a, b) => w(b) - w(a)).slice(0, KEEP).sort((a, b) => a.n - b.n || a.p - b.p || a.q - b.q);
  const used = [...new Set(kept.map((h) => h.n))].sort((a, b) => a - b), remap = new Map(used.map((n, i) => [n, i]));
  const Pin = used.map((n) => P[n]);
  const { E } = couplings(T, Pin);
  // membrane stiffness of the shallow shell, from a large in-plane basis
  const Pk = plateModes('clamped', { lam2Max: ZETA2_KC, mMax });
  const Ek = couplings(T, Pk).E, Kc = new Map();
  for (const a of Ek) for (const b of Ek) {
    if (a.n !== b.n || a.p > b.p) continue;
    const key = `${a.p},${b.p}`;
    Kc.set(key, (Kc.get(key) || 0) + (12 * (1 - NU * NU) * a.v * b.v) / Pk[a.n].lam2 ** 2);
  }
  const kc = [...Kc].map(([k, v]) => [...k.split(',').map(Number), v]).filter((e) => Math.abs(e[2]) > 1e-9);
  out[bc] = {
    modes: T.map((m) => ({ m: m.m, s: m.s, lam2: +m.lam2.toPrecision(9), R: Array.from({ length: NR }, (_, i) => f6(radial(m, i / (NR - 1)).R)) })),
    inplane: Pin.map((p) => ({ j: p.m, t: p.s, z4: +(p.lam2 ** 2).toPrecision(9) })),
    H: { n: kept.map((h) => remap.get(h.n)), p: kept.map((h) => h.p), q: kept.map((h) => h.q), v: kept.map((h) => f6(h.v)) },
    E: { n: E.map((e) => e.n), p: E.map((e) => e.p), v: E.map((e) => f6(e.v)) },
    Kc: { p: kc.map((e) => e[0]), q: kc.map((e) => e[1]), v: kc.map((e) => f6(e[2])) },
  };
  console.log(`${bc}: ${T.length} modes (m ≤ ${mMax}), ${Pin.length}/${P.length} in-plane modes, ${kept.length}/${H.length} couplings, ${E.length} curvature terms, Kc from ${Pk.length} in-plane modes`);
}
const url = new URL('../gongs/data/gong-modes.js', import.meta.url);
mkdirSync(new URL('./', url), { recursive: true });
writeFileSync(url, `// Generated by tools/gongs-modes.mjs — do not edit.\nexport default ${JSON.stringify(out)};\n`);
console.log(`gongs/data/gong-modes.js in ${((performance.now() - t0) / 1000).toFixed(1)} s`);

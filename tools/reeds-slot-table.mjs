// Solve Laplace's equation in a pickup slot over a range of reed heights and
// gaps, and write the capacitance table the reed piano's engine interpolates.
// Usage: node tools/reeds-slot-table.mjs        → reeds/src/slot-table.js  (a few minutes)
//
// Geometry and boundary conditions: see reeds/src/slot-field.js. Each reed
// height is solved on three nested grids (0.1, 0.05, 0.025 mm), each started
// from the one before, so SOR only has to remove short-wavelength error on
// the fine grid. C(y) is even in y (the slot is symmetric about the comb's
// mid-plane), so only y ≥ 0 is solved.

import { writeFileSync } from 'node:fs';
import { makeSlot, placeReed, solve, reedCharge, EPS0, SLOT_GEOM } from '../reeds/src/slot-field.js';

const mm = 1e-3;
const GAPS = [0.1, 0.15, 0.2, 0.3, 0.45, 0.65, 1.0, 1.5];
const DY = 0.05, YMAX = 4.5, DXS = [0.1, 0.05, 0.025];

// bilinear prolongation of a coarse solution onto a grid with half the step
function prolong(C, F) {
  for (let j = 0; j < F.ny; j++) for (let i = 0; i < F.nx; i++) {
    const ic = i >> 1, jc = j >> 1, fi = i & 1, fj = j & 1;
    const at = (a, b) => C.phi[Math.min(C.ny - 1, b) * C.nx + Math.min(C.nx - 1, a)];
    F.phi[j * F.nx + i] = 0.25 * ((2 - fi) * (2 - fj) * at(ic, jc) + fi * (2 - fj) * at(ic + 1, jc) + (2 - fi) * fj * at(ic, jc + 1) + fi * fj * at(ic + 1, jc + 1)) / 1;
  }
}

const table = [];
const t0 = performance.now();
for (const g of GAPS) {
  const grids = DXS.map((dx) => makeSlot({ ...SLOT_GEOM, g: g * mm }, dx * mm));
  const col = [];
  for (let n = 0; n * DY <= YMAX + 1e-9; n++) {
    const y = n * DY * mm;
    grids.forEach((S, k) => {
      if (k > 0) prolong(grids[k - 1], S);
      placeReed(S, y);
      solve(S, k === grids.length - 1 ? 1e-8 : 1e-6, 20000, 1.95);
    });
    col.push(reedCharge(grids[grids.length - 1]) / EPS0);
  }
  table.push(col);
  console.log(`gap ${g} mm: C′(0) = ${col[0].toFixed(3)} ε₀, C′(1 mm) = ${col[20].toFixed(3)} ε₀  (${((performance.now() - t0) / 1000).toFixed(0)} s)`);
}

const rows = table.map((col) => `  [${[...col].reverse().concat(col.slice(1)).map((v) => v.toFixed(4)).join(', ')}],`).join('\n');
const n = table[0].length;
writeFileSync(new URL('../reeds/src/slot-table.js', import.meta.url), `// slot-table.js — generated by tools/reeds-slot-table.mjs from the Laplace
// solution in reeds/src/slot-field.js; do not edit.
//
// Mutual capacitance per unit insertion depth between one reed and the comb,
// C′(y)/ε₀ (dimensionless), for reed heights y = ${-YMAX} … ${YMAX} mm above the comb's
// mid-plane in steps of ${DY} mm (rows), one row per gap in SLOT_GAPS (mm).
// Geometry: reed ${SLOT_GEOM.h / mm} × ${SLOT_GEOM.b / mm} mm, comb ${SLOT_GEOM.t / mm} mm thick, teeth ${SLOT_GEOM.tooth / mm} mm wide,
// grounded frame ±${SLOT_GEOM.H / mm} mm; grid ${DXS[DXS.length - 1]} mm.

export const SLOT_Y = { min: ${+(-YMAX * mm).toPrecision(6)}, step: ${+(DY * mm).toPrecision(6)}, n: ${2 * n - 1} };
export const SLOT_GAPS = [${GAPS.join(', ')}];
export const SLOT_C = [
${rows}
];
`);
console.log('wrote reeds/src/slot-table.js');

// Tune the cristal's stems as a maker does, by playing them: stroke each key's rod at the reference
// touch (the default pressure and stroke speed, velocity 0.6, one endless stroke), on the C++
// engine built as WebAssembly, measure the pitch of the rod's own motion once it has settled, and
// cut the stem sharp by as many cents as it sounds flat (stick–slip holds the rod a little each
// cycle, which lengthens it). Two passes, as the cut moves the touch a little. Writes
// native/instruments/cristal/cristal-tuning.h; then rebuild the wasm (native/README.md).
//
//   node tools/cristal-tuning.mjs          # measure, add to the table, write it (rebuild, run twice)
//   node tools/cristal-tuning.mjs --check  # measure every key on the build as it is

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { INSTRUMENT, DEFAULTS } from '../cristal/src/cristal-instrument.js';
import { loadEngine } from './engine.mjs';

const FS = 48000, KEY_MIN = 21, KEY_MAX = 108, VEL = 0.6;
const Engine = await loadEngine(INSTRUMENT);
const OUT = fileURLToPath(new URL('../native/instruments/cristal/cristal-tuning.h', import.meta.url));

// The rod's velocity from 1.5 s to 2.5 s after the key goes down (the engine's trace of the focused
// rod, read every 1024 samples), and its pitch from the rising zero crossings.
export function rodPitch(key, P = DEFAULTS, vel = VEL) {
  const e = new Engine(FS);
  e.setParams({ ...P, strokes: 'endless' });
  e.noteOn(key, vel);
  const bl = 128, L = new Float32Array(bl), R = new Float32Array(bl), T = 1024;
  const a = Math.round(1.5 * FS / T), b = Math.round(2.5 * FS / T), v = [];
  for (let c = 0; c < b; c++) {
    for (let i = 0; i < T / bl; i++) e.process(L, R, bl);
    if (c >= a) { const tr = e.trV, tw = e.tw; for (let i = 0; i < T; i++) v.push(tr[(tw + i) % T]); }
  }
  let first = -1, last = -1, n = 0;
  for (let i = 1; i < v.length; i++) if (v[i - 1] < 0 && v[i] >= 0) { const t = i - 1 + -v[i - 1] / (v[i] - v[i - 1]); if (first < 0) first = t; last = t; n++; }
  return n > 2 ? ((n - 1) * FS) / (last - first) : NaN;
}
const freq = (k) => 440 * 2 ** ((k - 69) / 12);
const measure = () => Array.from({ length: KEY_MAX - KEY_MIN + 1 }, (_, i) => 1200 * Math.log2(rodPitch(KEY_MIN + i) / freq(KEY_MIN + i)));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const cents = measure();
  const worst = cents.reduce((w, c, i) => (Math.abs(c) > Math.abs(w[0]) ? [c, i + KEY_MIN] : w), [0, 0]);
  console.log(`keys ${KEY_MIN}–${KEY_MAX}: worst ${worst[0].toFixed(2)} ¢ at ${worst[1]}; mean |·| ${(cents.reduce((s, c) => s + Math.abs(c), 0) / cents.length).toFixed(2)} ¢`);
  if (process.argv.includes('--check')) process.exit(0);
  const old = readFileSync(OUT, 'utf8').match(/CUT\[88\] = \{([^}]*)\}/)[1].split(',').map(Number).filter((x, i, a) => i < 88);
  const flat = old.map((f, i) => f - cents[i]); // sounding c cents off: cut it c cents the other way
  const rows = [];
  for (let i = 0; i < 88; i += 11) rows.push('  ' + flat.slice(i, i + 11).map((x) => x.toFixed(2)).join(', ') + ',');
  writeFileSync(OUT, `// cristal-tuning.h — generated by tools/cristal-tuning.mjs: how many cents sharp each key's stem is
// cut (A0–C8), so that its rod sounds the note when stroked at the reference touch (the default
// pressure and stroke, velocity 0.6): stick–slip holds the rod a little every cycle, which lengthens
// it, so a stem cut to the note's bending mode sounds flat. A maker tunes by playing, as this does.
#pragma once

namespace forte::cristal {
constexpr float CUT[88] = {
${rows.join('\n')}
};
} // namespace forte::cristal
`);
  console.log('wrote', OUT, '(rebuild the wasm, then run again until it is within 0.5 ¢)');
}

// carillon-native-table.mjs — carillon/src/bell-table.js (the tuned ribs and their modes, from the
// FEM: tools/carillon-profile.mjs) converted to C++ for the native port, number for number:
// native/instruments/carillon/bell-table.h. Only what the engine and the model use; the drawings'
// nodal circles and mode shapes stay in the JavaScript table.
// Usage: node tools/carillon-native-table.mjs            writes the header
//        node tools/carillon-native-table.mjs --check    fails if it is stale
// (tools/carillon-profile.mjs writes it too, after the table.)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { BELL_TABLE, STRIKE_GRID, SENS_GROUPS } from '../carillon/src/bell-table.js';
import { IDEAL } from '../carillon/src/partials.js';

export const headerFile = new URL('../native/instruments/carillon/bell-table.h', import.meta.url);
const PARTIALS = Object.keys(IDEAL); // hum, prime, tierce, quint, nominal, deciem, superquint, octnom
// the shortest text that reads back as the same double
const num = (x) => { if (!Number.isFinite(x)) throw new Error(`not a number: ${x}`); return String(x); };
const list = (a) => `{${a.map(num).join(', ')}}`;

export function nativeTable() {
  const out = [];
  out.push(`// bell-table.h — generated by tools/carillon-native-table.mjs from carillon/src/bell-table.js
// (itself generated by tools/carillon-profile.mjs from the axisymmetric FEM). Do not edit; after
// changing the table, run
//   node tools/carillon-native-table.mjs
// Per rib: profile, register and its keys, stations [r, z, t] (crown → lip, units of D), height H,
// volume (D³), λ of the prime, and its modes: family m, order k, ratio r to the prime, doublet factor
// kap, inner-surface motion w at STRIKE_GRID × H, ∫w² dS over the outer surface I and its radius a,
// sensitivities s (d ln f / d ln t per station group) and the named partial, if any.
#pragma once

namespace forte::carillon {

enum Partial : int { ${['none = -1', ...PARTIALS].join(', ')} };
enum Profile : int { minorThird, majorThird }; // the Bell profile parameter's choices

constexpr int STRIKE_N = ${STRIKE_GRID.length}, SENS_N = ${SENS_GROUPS.length}, STATION_N = ${BELL_TABLE.ribs[0].stations.length};
inline constexpr double STRIKE_GRID[STRIKE_N] = ${list(STRIKE_GRID)};

struct TableMode { int m, k; double r, kap, w[STRIKE_N], I, a, s[SENS_N]; Partial name; };
struct Rib {
  Profile profile;
  const char *registerName;
  int lo, hi;
  double heavy, stations[STATION_N][3], H, volume, lamPrime;
  const TableMode *modes;
  int modeCount;
};
`);
  const names = [];
  let most = 0;
  for (const r of BELL_TABLE.ribs) {
    const id = `kModes_${r.profile}_${r.register}`;
    names.push(id);
    most = Math.max(most, r.modes.length);
    out.push(`inline const TableMode ${id}[] = {`);
    for (const m of r.modes) {
      if (m.w.length !== STRIKE_GRID.length || m.s.length !== SENS_GROUPS.length) throw new Error(`${id}: a mode's table has the wrong length`);
      out.push(`  {${m.m}, ${m.k}, ${num(m.r)}, ${num(m.kap)}, ${list(m.w)}, ${num(m.I)}, ${num(m.a)}, ${list(m.s)}, ${m.n ? m.n : 'none'}},`);
    }
    out.push('};');
  }
  out.push(`
constexpr int MODES_MAX = ${most}; // the most modes of any rib
inline const Rib RIBS[] = {`);
  BELL_TABLE.ribs.forEach((r, i) => {
    out.push(`  {${r.profile}Third, "${r.register}", ${r.lo}, ${r.hi}, ${num(r.heavy)}, {${r.stations.map(list).join(', ')}}, ${num(r.H)}, ${num(r.volume)}, ${num(r.lamPrime)}, ${names[i]}, ${r.modes.length}},`);
  });
  out.push(`};
constexpr int RIB_N = ${BELL_TABLE.ribs.length};

} // namespace forte::carillon
`);
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = nativeTable();
  if (process.argv.includes('--check')) {
    if (!existsSync(headerFile) || readFileSync(headerFile, 'utf8') !== text) {
      console.error('stale: native/instruments/carillon/bell-table.h (run node tools/carillon-native-table.mjs)');
      process.exit(1);
    }
  } else {
    writeFileSync(headerFile, text);
    console.log('native/instruments/carillon/bell-table.h');
  }
}

// Regulate the brass as a voicer would an organ: for each horn and each key, play it at the
// defaults, mezzo-forte (the computer keys' velocity), measure its level once it has spoken, and set
// its gain so that every key comes out at the same level. A horn's own loudness changes with its
// register and its partial (its second partial is weak, its high ones strong), and so would every
// key's if left alone. Writes native/instruments/brass/brass-levels.h (then rebuild the wasm).
//
//   node tools/brass-levels.mjs           # measure, and write the table
//   node tools/brass-levels.mjs --check   # measure the build as it is: each key against the target

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { INSTRUMENT, DEFAULTS, HORNS } from '../brass/src/brass-instrument.js';
import { wasmModel } from '../brass/src/brass-wasm.js';
import { loadEngine } from './engine.mjs';

const FS = 48000, LO = 21, HI = 108, TARGET = -28; // dB rms of the dry output, mezzo-forte
const BrassEngine = await loadEngine(INSTRUMENT);
const M = await wasmModel();

// A key's level (dB rms) from 0.7 to 1.2 s, and the gain the build gave it (dB).
function level(horn, key) {
  const P = { ...DEFAULTS, horn }, e = new BrassEngine(FS);
  e.setParams(P);
  e.noteOn(key, DEFAULTS.velocity);
  const L = new Float32Array(128), R = new Float32Array(128);
  let s = 0, n = 0;
  for (let t = 0; t < 1.2 * FS; t += 128) {
    e.process(L, R, 128);
    if (t >= 0.7 * FS) for (let i = 0; i < 128; i++) { s += L[i] * L[i] + R[i] * R[i]; n += 2; }
  }
  e.destroy();
  return { dB: 10 * Math.log10(s / n + 1e-30), gain: 20 * Math.log10(M.plan(key, P).gain) };
}

const check = process.argv.includes('--check');
const table = [];
for (const [horn] of HORNS) {
  const raw = [], off = [];
  for (let key = LO; key <= HI; key++) {
    const m = level(horn, key);
    raw.push(m.dB - m.gain);
    off.push(m.dB - TARGET);
  }
  if (check) {
    const worst = off.reduce((a, b) => (Math.abs(b) > Math.abs(a) ? b : a), 0);
    console.log(`${horn}: worst ${worst.toFixed(1)} dB; ${off.map((d, i) => `${LO + i}:${d.toFixed(0)}`).join(' ')}`);
    continue;
  }
  // (each key against the median of it and its neighbours, so one key's luck does not set its gain)
  const med = raw.map((_, i) => [raw[Math.max(0, i - 1)], raw[i], raw[Math.min(raw.length - 1, i + 1)]].sort((a, b) => a - b)[1]);
  table.push(med.map((r) => Math.max(-45, Math.min(45, TARGET - r))));
  console.log(`${horn}: ${table.at(-1).map((d) => d.toFixed(1)).join(' ')}`);
}
if (!check) {
  const rows = table.map((t) => `  {${t.map((d) => d.toFixed(1)).join(', ')}},`).join('\n');
  const out = `// brass-levels.h — generated by tools/brass-levels.mjs. Do not edit.
// Each key's regulation (dB) per horn: what brings its mezzo-forte at the defaults to the same loudness.
#pragma once
namespace forte::brass {
constexpr int LEVELS_LO = ${LO}, LEVELS_N = ${HI - LO + 1};
constexpr float LEVELS[${table.length}][${HI - LO + 1}] = {
${rows}
};
} // namespace forte::brass
`;
  writeFileSync(fileURLToPath(new URL('../native/instruments/brass/brass-levels.h', import.meta.url)), out);
  console.log('wrote native/instruments/brass/brass-levels.h (rebuild the wasm)');
}

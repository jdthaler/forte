// Shape every vibraphone bar's undercut so that bending modes 1, 2, 3 sit at
// exactly 1 : 4 : 10, and write the table the instrument plays from.
// Usage: node tools/vibraphone-bars.mjs        (→ vibraphone/src/bar-table.js, about half a second)
//
// Each bar is aluminium, h₀ = 12.7 mm thick, its width graded from 57 mm (F3) to
// 38 mm (F6). The cut is a thin flat centre (half-width c) with cosine sides out
// to ±a. c/a is fixed per key, rising from 0.22 in the bass (a wide arch) to
// 0.85 in the treble (a narrow, flat-bottomed slot); the optimiser
// (tuneUndercut in vibraphone/src/bar.js) finds a, the depth d and the length L.

import { writeFileSync } from 'node:fs';
import { tuneUndercut, bendingFreqs3 } from '../vibraphone/src/bar.js';
import { KEY_LO, KEY_HI, barBlank, keyFreq } from '../vibraphone/src/vibraphone-model.js';

const rows = [];
let start = { A: 0.75, D: 0.62, L: 0.37 };
const t0 = performance.now();
for (let k = KEY_LO; k <= KEY_HI; k++) {
  const { b, h0, cf } = barBlank(k);
  const r = tuneUndercut({ f1: keyFreq(k), b, h0, cf, start });
  const f = bendingFreqs3(r.cut, r.L, b);
  const c2 = 1200 * Math.log2(f[1] / f[0] / 4), c3 = 1200 * Math.log2(f[2] / f[0] / 10);
  if (Math.max(Math.abs(c2), Math.abs(c3)) > 0.01) throw new Error(`key ${k}: ${c2.toFixed(3)} ¢, ${c3.toFixed(3)} ¢`);
  rows.push([k, +r.L.toFixed(7), +r.A.toFixed(7), +r.D.toFixed(7)]);
  start = { A: r.A, D: r.D, L: r.L * 2 ** (-1 / 24) };
  console.log(`${k}  L ${(100 * r.L).toFixed(2)} cm  a/(L/2) ${r.A.toFixed(4)}  c/a ${cf.toFixed(3)}  d/h0 ${r.D.toFixed(4)}  ratios ${(f[1] / f[0]).toFixed(5)} ${(f[2] / f[0]).toFixed(5)}`);
}
const src = `// bar-table.js — generated by tools/vibraphone-bars.mjs; do not edit.
// The tuned (1 : 4 : 10) bars: [key, length L (m), a/(L/2), d/h₀]. The
// thickness h₀, the width b and c/a come from barBlank(key) in vibraphone-model.js.
export const BAR_TABLE = [
${rows.map((r) => `  [${r.join(', ')}],`).join('\n')}
];
`;
writeFileSync(new URL('../vibraphone/src/bar-table.js', import.meta.url), src);
console.log(`vibraphone/src/bar-table.js: ${rows.length} bars in ${(performance.now() - t0).toFixed(0)} ms`);

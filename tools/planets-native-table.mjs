// planets-native-table.mjs — the Ringing Planets' modes (tools/planets-modes.mjs, from the models in
// planets/src/planets-models.js) as a C++ header for the engine: native/instruments/planets/planets-table.h.
// Per planet: radius, surface gravity, sidereal day, and every multiplet up to RATIO × its 0S2 and
// degree LMAX: type, n, l, frequency, Q, spin splitting χ, the eigenfunctions at the surface (U, V, P;
// or W) and at DEPTHS source depths (U, U', V, V'; or W, W'), in the solver's units (km, g/cm³, s;
// ∫ρ(U² + V²) r² dr = 1).
// Usage: node tools/planets-native-table.mjs            writes the header (about a minute)
//        node tools/planets-native-table.mjs --check    exit 1 if it is stale

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { solvePlanet, evalMode } from './planets-modes.mjs';
import { PLANETS, gravityAt } from '../planets/src/planets-models.js';

export const headerFile = new URL('../native/instruments/planets/planets-table.h', import.meta.url);
export const RATIO = 12, LMAX = 40, DEPTHS = 16;
const DMAX = { earth: 700, mars: 800, moon: 1200 }; // km: the deepest quakes worth a table
const num = (x) => { if (!Number.isFinite(x)) throw new Error(`not a number: ${x}`); return Number(x.toPrecision(7)).toString(); };

export function nativeTable() {
  const out = [`// planets-table.h — generated by tools/planets-native-table.mjs (the normal-mode solver,
// tools/planets-modes.mjs, on planets/src/planets-models.js). Do not edit; after changing either, run
//   node tools/planets-native-table.mjs
// Units: km, g/cm³, s. Eigenfunctions normalised so that ∫ρ(U² + V²) r² dr = 1 (∫ρW² r² dr = 1).
#pragma once

namespace forte::planets {

constexpr int kDepths = ${DEPTHS};
struct TableMode {
  int type, n, l;     // type 0: spheroidal nSl, 1: toroidal nTl
  double f, Q, chi;   // Hz (dispersed to its own frequency), quality factor, spin splitting (ω_m = ω + mχΩ)
  float U, V, P;      // at the surface: U, V and the potential P (toroidal: W, 0, 0)
  float src[kDepths][4]; // at each source depth: U, U', V, V' (toroidal: W, W', 0, 0)
};
struct TablePlanet {
  const char *id;
  double R, g, day, f0S2; // km, km/s², s, Hz
  double depth[kDepths];  // km
  const TableMode *modes;
  int count;
};
`];
  const planets = [];
  for (const P of PLANETS) {
    const s2 = solvePlanet(P, { fmax: 0.002, lmax: 2, types: 'S' }).find((m) => m.n === 0 && m.l === 2);
    const modes = solvePlanet(P, { fmax: s2.f * RATIO, lmax: LMAX, meshF: 2.2 });
    modes.sort((a, b) => a.f - b.f);
    const dmax = DMAX[P.id];
    const depth = Array.from({ length: DEPTHS }, (_, i) => dmax * (i / (DEPTHS - 1)) ** 2);
    const rows = modes.map((m) => {
      const S = m.type === 'S';
      const top = evalMode(m.sol, m.c, P.R);
      const surf = S ? [top.U, top.V, top.P] : [top.W, 0, 0];
      const src = depth.map((d) => {
        const e = evalMode(m.sol, m.c, P.R - Math.max(d, 1e-6));
        return S ? [e.U, e.dU, e.V, e.dV] : [e.W, e.dW, 0, 0];
      });
      return `  {${S ? 0 : 1}, ${m.n}, ${m.l}, ${num(m.f)}, ${num(m.Q)}, ${num(m.chi)}, ${surf.map(num).join(', ')}, {${src.map((r) => `{${r.map(num).join(', ')}}`).join(', ')}}},`;
    });
    out.push(`inline const TableMode k${P.id[0].toUpperCase()}${P.id.slice(1)}Modes[] = {\n${rows.join('\n')}\n};`);
    planets.push(`  {"${P.id}", ${num(P.R)}, ${num(gravityAt(P, P.R) / 1000)}, ${num(P.day)}, ${num(s2.f)}, {${depth.map(num).join(', ')}}, k${P.id[0].toUpperCase()}${P.id.slice(1)}Modes, ${modes.length}},`);
    console.error(`${P.id}: ${modes.length} multiplets, 0S2 ${(s2.f * 1000).toFixed(4)} mHz`);
  }
  out.push(`inline const TablePlanet kPlanets[] = {\n${planets.join('\n')}\n};\n\n} // namespace forte::planets\n`);
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = nativeTable();
  if (process.argv.includes('--check')) {
    if (!existsSync(headerFile) || readFileSync(headerFile, 'utf8') !== text) { console.error('native/instruments/planets/planets-table.h is stale: run node tools/planets-native-table.mjs'); process.exit(1); }
    console.log('native/instruments/planets/planets-table.h is fresh');
  } else {
    writeFileSync(headerFile, text);
    console.log('native/instruments/planets/planets-table.h');
  }
}

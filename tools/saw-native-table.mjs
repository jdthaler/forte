// saw-native-table.mjs — the musical saw's trapped modes, solved once and written as a C++ table
// for its native port: native/instruments/saw/saw-table.h.
//
// The blade is a shallow shell bent along its length, with the curvature b(x) = b′x changing sign
// at the S's inflection. A mode with the shape φ(y) across the blade (wavenumber q = βₘ/W) and f(x)
// along it obeys Donnell's shallow-shell equations (Shankar, Bryde & Mahadevan 2022, eqs. 1–2):
//   ρh ω² f = κ (∂ₓ² − q²)² f + Yh q⁴ b χ,   (∂ₓ² − q²)² χ = b f,
// so that, with X = q x, L = ∂²_X − 1 and Ω = ω / (a q²), a² = κ/ρh:
//   Ω² f = L² f + ε² X L⁻² (X f),   ε = c b′ / (a q³),   c² = Y/ρ.
// One number, ε, sets every trapped mode. This tool solves that eigenproblem by finite
// differences on a line long enough for the mode to have died away (Dirichlet ends), for ε from
// 10⁻³ to 30, and keeps the lowest three modes' Ω and their RMS widths (in X). For small ε the
// modes are wide and L ≈ −1 + ∂²_X/… gives a harmonic well: Ω² ≈ 1 + (2n + 1)√2 ε, widths
// √((n + ½)·√2/ε) (test/saw-tests.mjs checks both limits, and the table recomputed).
//
// Usage: node tools/saw-native-table.mjs           writes the header
//        node tools/saw-native-table.mjs --check   exit 1 if it is stale

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { symEig } from '../shared/linalg.js';

export const headerFile = new URL('../native/instruments/saw/saw-table.h', import.meta.url);
export const GRID = { lo: -3, step: 0.0625, n: 73 }; // log10 ε: 10⁻³ … 10^1.5
export const MODES = 3;

// The trapped modes for one ε: [{ W2: Ω², rms }] for the lowest `count`, rms in X = q x.
export function solveTrapped(eps, { span = 10, res = 12, maxN = 420, count = MODES } = {}) {
  const l = Math.sqrt(Math.SQRT2 / eps);   // the harmonic well's width
  const Xm = Math.max(span * l, 8);
  const dX = Math.max(Math.min(l / res, 0.25), (2 * Xm) / maxN);
  const n = Math.round((2 * Xm) / dX) - 1, X = Float64Array.from({ length: n }, (_, i) => -Xm + (i + 1) * dX);
  const d = -2 / (dX * dX) - 1, o = 1 / (dX * dX); // L = D² − 1, tridiagonal
  // L⁻¹, column by column (Thomas); symmetric
  const inv = Array.from({ length: n }, () => new Float64Array(n));
  const cp = new Float64Array(n), dp = new Float64Array(n);
  for (let j = 0; j < n; j++) {
    cp[0] = o / d; dp[0] = (j === 0 ? 1 : 0) / d;
    for (let i = 1; i < n; i++) { const m = d - o * cp[i - 1]; cp[i] = o / m; dp[i] = ((i === j ? 1 : 0) - o * dp[i - 1]) / m; }
    const x = inv[j]; x[n - 1] = dp[n - 1];
    for (let i = n - 2; i >= 0; i--) x[i] = dp[i] - cp[i] * x[i + 1];
  }
  const H = Array.from({ length: n }, () => new Array(n).fill(0));
  for (let i = 0; i < n; i++) {
    for (let j = i; j < n; j++) {
      let s = 0; const a = inv[i], b = inv[j];
      for (let k = 0; k < n; k++) s += a[k] * b[k];
      H[i][j] = H[j][i] = eps * eps * X[i] * X[j] * s;
    }
  }
  for (let i = 0; i < n; i++) { // + L², pentadiagonal
    H[i][i] += d * d + o * o * ((i > 0) + (i < n - 1));
    if (i + 1 < n) { H[i][i + 1] += 2 * d * o; H[i + 1][i] += 2 * d * o; }
    if (i + 2 < n) { H[i][i + 2] += o * o; H[i + 2][i] += o * o; }
  }
  const ev = symEig(H, n);
  const idx = Array.from(ev.keys()).sort((a, b) => ev[a] - ev[b]);
  return idx.slice(0, count).map((k) => {
    let s0 = 0, s2 = 0;
    for (let i = 0; i < n; i++) { const v = H[i][k]; s0 += v * v; s2 += v * v * X[i] * X[i]; }
    return { W2: ev[k], rms: Math.sqrt(s2 / s0) };
  });
}

export function table() {
  const omega = Array.from({ length: MODES }, () => []), rms = Array.from({ length: MODES }, () => []);
  for (let i = 0; i < GRID.n; i++) {
    const m = solveTrapped(10 ** (GRID.lo + i * GRID.step));
    for (let k = 0; k < MODES; k++) { omega[k].push(Number(Math.sqrt(m[k].W2).toPrecision(9))); rms[k].push(Number(m[k].rms.toPrecision(7))); }
  }
  return { omega, rms };
}

const num = (x) => { if (!Number.isFinite(x)) throw new Error(`not a number: ${x}`); const s = String(x); return /[.e]/.test(s) ? s : `${s}.0`; };
const list = (a) => a.map(num).join(', ');

export function nativeTable(T = table()) {
  return `// saw-table.h — generated by tools/saw-native-table.mjs (the shallow-shell eigenproblem it
// solves is in its header). Do not edit; to change it, run
//   node tools/saw-native-table.mjs
//
// The musical saw's trapped modes for ε = c b′ / (a q³) at log10 ε = EPS_LO + i·EPS_STEP:
// OMEGA[n][i], the nth mode's ω / (a q²), and RMS[n][i], its RMS width along the blade, in units of 1/q.
#pragma once

namespace forte::saw::table {

inline constexpr double EPS_LO = ${num(GRID.lo)}, EPS_STEP = ${num(GRID.step)};
inline constexpr int NEPS = ${GRID.n}, NMODES = ${MODES};
inline constexpr double OMEGA[NMODES][NEPS] = {
${T.omega.map((r) => `  {${list(r)}},`).join('\n')}
};
inline constexpr double RMS[NMODES][NEPS] = {
${T.rms.map((r) => `  {${list(r)}},`).join('\n')}
};

} // namespace forte::saw::table
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = nativeTable();
  if (process.argv.includes('--check')) {
    if (!existsSync(headerFile) || readFileSync(headerFile, 'utf8') !== text) { console.error('native/instruments/saw/saw-table.h is stale: run node tools/saw-native-table.mjs'); process.exit(1); }
    console.log('native/instruments/saw/saw-table.h is fresh');
  } else {
    writeFileSync(headerFile, text);
    console.log('native/instruments/saw/saw-table.h');
  }
}

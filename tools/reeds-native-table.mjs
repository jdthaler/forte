// reeds-native-table.mjs — the reed piano's slot table (reeds/src/slot-table.js, made by
// tools/reeds-slot-table.mjs from the Laplace solution) as a C++ header for its native port:
// native/instruments/reeds/slot-table.h. The same numbers, converted, not solved again.
//
// Usage: node tools/reeds-native-table.mjs           writes the header
//        node tools/reeds-native-table.mjs --check   exit 1 if it is stale
// (tools/reeds-slot-table.mjs writes it too, after the table.)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { SLOT_Y, SLOT_GAPS, SLOT_C } from '../reeds/src/slot-table.js';

export const headerFile = new URL('../native/instruments/reeds/slot-table.h', import.meta.url);
// the shortest text that reads back as the same double
const num = (x) => { if (!Number.isFinite(x)) throw new Error(`not a number: ${x}`); const s = String(x); return /[.e]/.test(s) ? s : `${s}.0`; };
const list = (a) => a.map(num).join(', ');

export function nativeTable(Y = SLOT_Y, gaps = SLOT_GAPS, C = SLOT_C) {
  if (C.length !== gaps.length || C.some((row) => row.length !== Y.n)) throw new Error('slot table: rows and gaps disagree');
  return `// slot-table.h — generated by tools/reeds-native-table.mjs from reeds/src/slot-table.js (made by
// tools/reeds-slot-table.mjs from the Laplace solution in reeds/src/slot-field.js). Do not edit;
// after changing the table, run
//   node tools/reeds-native-table.mjs
//
// Mutual capacitance per unit insertion depth between one reed and the comb, C′(y)/ε₀, for reed
// heights y = SLOT_Y.min + i·SLOT_Y.step (m) above the comb's mid-plane, one row per gap in
// SLOT_GAPS (mm).
#pragma once

namespace forte::reeds {

struct SlotY { double min, step; int n; };
inline constexpr SlotY SLOT_Y = {${num(Y.min)}, ${num(Y.step)}, ${Y.n}};
inline constexpr int SLOT_NGAPS = ${gaps.length};
inline constexpr double SLOT_GAPS[SLOT_NGAPS] = {${list(gaps)}};
inline constexpr double SLOT_C[SLOT_NGAPS][${Y.n}] = {
${C.map((row) => `  {${list(row)}},`).join('\n')}
};

} // namespace forte::reeds
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = nativeTable();
  if (process.argv.includes('--check')) {
    if (!existsSync(headerFile) || readFileSync(headerFile, 'utf8') !== text) { console.error('native/instruments/reeds/slot-table.h is stale: run node tools/reeds-native-table.mjs'); process.exit(1); }
    console.log('native/instruments/reeds/slot-table.h is fresh');
  } else {
    writeFileSync(headerFile, text);
    console.log('native/instruments/reeds/slot-table.h');
  }
}

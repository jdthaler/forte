// Tune the Hurdy-Gurdy in the engine, as a maker does: bow each note alone at the default crank
// speed and pressure (48 kHz), measure how far it sounds from its note, and turn its tangent (or the
// drone's peg) by that much. The bowed note runs flat of the free string, the more so the higher the
// note and the further along its string the wheel sits. Six passes, starting from the table already
// there, each note keeping the setting that came closest; the corrections are tried in the
// WebAssembly as it is, so no rebuild is needed until the end. Then rebuild (native/README.md), and
// --check measures the build.
// Usage: node tools/hurdygurdy-tuning.mjs            (→ native/instruments/hurdygurdy/hurdygurdy-tuning.h)
//        node tools/hurdygurdy-tuning.mjs --check    (measures every note as built: exit 1 if one is 2 ¢ off or more)

import { writeFileSync } from 'node:fs';
import { INSTRUMENT, DEFAULTS } from '../hurdygurdy/src/hurdygurdy-instrument.js';
import { RANGE } from '../hurdygurdy/src/hurdygurdy-params.js';
import { wasmModel } from '../hurdygurdy/src/hurdygurdy-wasm.js';
import { Player } from './headless.mjs';
import { loadEngine } from './engine.mjs';
import { fft } from './audio-util.mjs';

const FS = 48000, PASSES = 6;
const HEADER = new URL('../native/instruments/hurdygurdy/hurdygurdy-tuning.h', import.meta.url);
const Engine = await loadEngine(INSTRUMENT), M = await wasmModel();
const keyFreq = (k) => 440 * 2 ** ((k - 69) / 12);

// The frequency of the spectral peak nearest f (within 3 %), Hann-windowed, zero-padded and
// interpolated: a bowed note is periodic, so its fundamental is its pitch.
export function peakFreq(x, f, fs = FS) {
  const N = 1 << 18, re = new Float64Array(N), im = new Float64Array(N);
  for (let i = 0; i < x.length && i < N; i++) re[i] = x[i] * (0.5 - 0.5 * Math.cos((2 * Math.PI * i) / x.length));
  fft(re, im);
  const mag = (k) => Math.hypot(re[k], im[k]);
  let best = Math.round((f * 0.97 * N) / fs);
  for (let k = best; k <= Math.round((f * 1.03 * N) / fs); k++) if (mag(k) > mag(best)) best = k;
  const a = Math.log(mag(best - 1)), b = Math.log(mag(best)), c = Math.log(mag(best + 1));
  return ((best + (0.5 * (a - c)) / (a - 2 * b + c)) * fs) / N;
}

// The notes: each key on the chanterelles alone (the second in unison), then each drone alone, the
// wheel turning steadily, measured over 2.4 s from 1 s in: the two chanterelles, coupled on their
// bridge, take a while to fall into step, and wander a little when they do.
const quiet = { ...DEFAULTS, uneven: 0, unison: 0, chanterelles: false, trompette: false, mouche: false, petit: false, gros: false };
export const NOTES = [
  ...Array.from({ length: RANGE[1] - RANGE[0] + 1 }, (_, i) => ({ row: i, key: RANGE[0] + i, P: { ...quiet, chanterelles: true }, ev: [[0, 'on', RANGE[0] + i, 0.5]] })),
  { row: 100, key: 62, P: { ...quiet, trompette: true, keep: true, tirant: 8 } },
  { row: 101, key: 60, P: { ...quiet, trompette: true, tromNote: 'c4', keep: true, tirant: 8 } },
  { row: 102, key: 55, P: { ...quiet, mouche: true, keep: true } },
  { row: 103, key: 48, P: { ...quiet, petit: true, keep: true } },
  { row: 104, key: 43, P: { ...quiet, gros: true, keep: true } },
];
export function measure(n) {
  const [L] = new Player(INSTRUMENT, Engine, FS, n.P).render(3.4, n.ev ?? []);
  return peakFreq(L.subarray(Math.round(1.0 * FS)), keyFreq(n.key));
}
const cents = (n) => 1200 * Math.log2(measure(n) / keyFreq(n.key));

if (process.argv.includes('--check')) {
  let worst = 0, at = '';
  for (const n of NOTES) { const c = cents(n); if (Math.abs(c) > Math.abs(worst)) { worst = c; at = `${n.row < 100 ? `key ${n.key}` : `drone ${n.row - 100}`}`; } }
  console.log(`worst ${worst.toFixed(3)} ¢ (${at})`);
  process.exit(Math.abs(worst) < 2 ? 0 : 1);
}

// The open string first (every tangent is set from it), then the tangents and the drones.
const best = new Map();
for (let pass = 0; pass < PASSES; pass++) {
  let worst = 0, at = '';
  for (const n of NOTES) {
    const was = M.tune(n.row), c = cents(n);
    if (Math.abs(c) > Math.abs(worst)) { worst = c; at = n.row < 100 ? `key ${n.key}` : `drone ${n.row - 100}`; }
    if (!(Math.abs(c) >= (best.get(n.row)?.c ?? Infinity))) best.set(n.row, { t: was, c: Math.abs(c) });
    M.setTune(n.row, +(was - c).toFixed(3));
  }
  console.log(`pass ${pass + 1}: worst ${worst.toFixed(2)} ¢ before it (${at})`);
}
const row = (r) => +best.get(r).t.toFixed(2);
writeFileSync(HEADER, `// hurdygurdy-tuning.h — generated by tools/hurdygurdy-tuning.mjs; do not edit.
// How far each tangent and each drone's peg is turned (cents sharp of the free string's note), so
// that the note bowed at the default crank speed and pressure sounds in tune (48 kHz, measured in
// the engine). TANGENTS: the open chanterelles (G4), then each key's tangent to G6; DRONES: the
// trompette in D4 and in C4, the mouche, the petit and the gros bourdon.
#pragma once

namespace forte::hurdygurdy {

inline constexpr double TANGENTS[] = {${NOTES.filter((n) => n.row < 100).map((n) => row(n.row)).join(', ')}};
inline constexpr double DRONES[] = {${[100, 101, 102, 103, 104].map(row).join(', ')}};

} // namespace forte::hurdygurdy
`);
console.log('wrote native/instruments/hurdygurdy/hurdygurdy-tuning.h: rebuild, then --check');

// gongs-native-table.mjs — the gong's plate tables (gongs/data/gong-modes.js, made by
// tools/gongs-modes.mjs) as a C++ header for its native port: the same numbers, converted, not
// computed again.
//
// Usage: node tools/gongs-native-table.mjs           writes native/instruments/gongs/gong-modes.h
//        node tools/gongs-native-table.mjs --check   exit 1 if that file is stale

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import TABLE from '../gongs/data/gong-modes.js';

const file = new URL('../native/instruments/gongs/gong-modes.h', import.meta.url);
const num = (v) => { const s = String(v); return /[.e]/.test(s) ? s : `${s}.0`; }; // every value as JavaScript prints it
const list = (a, f = num) => a.map(f).join(', ');
const int = (v) => String(v);

export function header() {
  for (const bc of ['free', 'clamped']) { // the indices fit a byte
    const T = TABLE[bc];
    if (Math.max(T.modes.length, T.inplane.length) > 255) throw new Error(`${bc}: too many modes for the header's byte indices`);
  }
  const out = [
    '// gong-modes.h — generated by tools/gongs-native-table.mjs from gongs/data/gong-modes.js (made by',
    '// tools/gongs-modes.mjs). Do not edit; after changing the tables, run',
    '//   node tools/gongs-native-table.mjs',
    '//',
    `// ${TABLE.note}`,
    '#pragma once',
    '',
    '#include <cstdint>',
    '',
    'namespace forte::gongs::table {',
    '',
    `constexpr double NU = ${num(TABLE.nu)};`,
    `constexpr int NR = ${TABLE.nr}; // radial samples on r = 0, 1/${TABLE.nr - 1}, …, 1`,
    '',
    'struct Mode { int m, s; double lam2; double R[NR]; }; // transverse mode: cos mθ, s, λ², radial shape',
    'struct Inplane { int j, t; double z4; };            // Airy (in-plane) mode: its ζ⁴',
    'struct Table {',
    '  const Mode *modes; int N;',
    '  const Inplane *inplane; int NS;',
    '  const uint8_t *Hn, *Hp, *Hq; const double *Hv; int nH; // ∫ Ψ_n L(Φ_p, Φ_q) dA',
    '  const uint8_t *En, *Ep; const double *Ev; int nE;      // ∫ Ψ_n ∇²Φ_p dA',
    '  const uint8_t *Kp, *Kq; const double *Kv; int nK;      // membrane stiffness per κ²',
    '};',
    '',
  ];
  for (const bc of ['free', 'clamped']) {
    const T = TABLE[bc], P = bc[0].toUpperCase() + bc.slice(1);
    out.push(`// ---- ${bc} rim ----`);
    out.push(`inline constexpr Mode k${P}Modes[] = {`);
    for (const md of T.modes) out.push(`  {${md.m}, ${md.s}, ${num(md.lam2)}, {${list(md.R)}}},`);
    out.push('};');
    out.push(`inline constexpr Inplane k${P}Inplane[] = {${T.inplane.map((p) => `{${p.j}, ${p.t}, ${num(p.z4)}}`).join(', ')}};`);
    out.push(`inline constexpr uint8_t k${P}Hn[] = {${list(T.H.n, int)}};`);
    out.push(`inline constexpr uint8_t k${P}Hp[] = {${list(T.H.p, int)}};`);
    out.push(`inline constexpr uint8_t k${P}Hq[] = {${list(T.H.q, int)}};`);
    out.push(`inline constexpr double k${P}Hv[] = {${list(T.H.v)}};`);
    out.push(`inline constexpr uint8_t k${P}En[] = {${list(T.E.n, int)}};`);
    out.push(`inline constexpr uint8_t k${P}Ep[] = {${list(T.E.p, int)}};`);
    out.push(`inline constexpr double k${P}Ev[] = {${list(T.E.v)}};`);
    out.push(`inline constexpr uint8_t k${P}Kp[] = {${list(T.Kc.p, int)}};`);
    out.push(`inline constexpr uint8_t k${P}Kq[] = {${list(T.Kc.q, int)}};`);
    out.push(`inline constexpr double k${P}Kv[] = {${list(T.Kc.v)}};`);
    out.push(`inline constexpr Table k${P} = {k${P}Modes, ${T.modes.length}, k${P}Inplane, ${T.inplane.length}, k${P}Hn, k${P}Hp, k${P}Hq, k${P}Hv, ${T.H.n.length}, `
      + `k${P}En, k${P}Ep, k${P}Ev, ${T.E.n.length}, k${P}Kp, k${P}Kq, k${P}Kv, ${T.Kc.p.length}};`);
    out.push('');
  }
  out.push('inline constexpr const Table *kTables[] = {&kFree, &kClamped}; // by the Rim parameter\'s index');
  out.push('', '} // namespace forte::gongs::table', '');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = header();
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error('native/instruments/gongs/gong-modes.h is stale: run node tools/gongs-native-table.mjs'); process.exit(1); }
    console.log('native/instruments/gongs/gong-modes.h is fresh');
  } else {
    writeFileSync(file, text);
    console.log('native/instruments/gongs/gong-modes.h');
  }
}

// gen-native-vectors.mjs — what the shared JavaScript computes, for native/tests to check the C++
// ports against (native/tests/js-vectors.h): shared/dsp.js, shared/impulses.js (the random
// sequence and the impulse responses), shared/linalg.js and the output chain (shared/chain.js,
// offline as tools/headless.mjs applies it).
//
// Usage: node tools/gen-native-vectors.mjs           (writes native/tests/js-vectors.h)
//        node tools/gen-native-vectors.mjs --check   (exit 1 if it is stale)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { modeCoeffs, Biquad, OnePole, DCBlock, Delay, keyPan } from '../shared/dsp.js';
import { soundboardIR, roomIR } from '../shared/impulses.js';
import { symEig, genEig } from '../shared/linalg.js';
import { FS_SHIM, webAudioIR } from './audio-util.mjs';
import { applyChain } from './headless.mjs';

const R = new URL('../', import.meta.url), FILE = new URL('native/tests/js-vectors.h', R);
const out = [];
const w = (s = '') => out.push(s);
const num = (x) => (Number.isFinite(x) ? (Object.is(x, -0) ? '-0.0' : String(x)) : x > 0 ? 'INFINITY' : '-INFINITY');
const arr = (name, xs, type = 'double') => w(`inline const ${type} ${name}[] = {${Array.from(xs, num).join(', ')}};`);

// the generator of shared/impulses.js (not exported there), for its sequence
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
// a seeded noise burst, the chain's test input
function burst(n, seed) {
  const r = rng(seed), x = new Float64Array(n);
  for (let i = 0; i < n; i++) x[i] = Math.fround((r() * 2 - 1) * Math.exp(-i / 4800) * 0.3);
  return x;
}

w('// js-vectors.h — generated by tools/gen-native-vectors.mjs from the shared JavaScript. Do not edit;');
w('// after changing shared/dsp.js, impulses.js, linalg.js or chain.js, run node tools/gen-native-vectors.mjs');
w('#pragma once');
w();
w('#include <cmath>');
w();
w('namespace js {');
w();
w('// shared/impulses.js: the first draws of the seeded generators');
for (const seed of [11, 18, 101, 102]) { const r = rng(seed); arr(`kRng${seed}`, Array.from({ length: 64 }, r)); }
w();
w('// shared/dsp.js');
const modes = [[261.63, 1.5, 48000], [4186, 30, 44100], [55, 0.2, 96000], [12000, 300, 48000]];
arr('kModeIn', modes.flat());
arr('kModeOut', modes.flatMap(([f, s, fs]) => { const c = modeCoeffs(f, s, fs); return [c.a1, c.a2, c.b]; }));
const bq = [['lp', 1000, 0.7, 48000, 0], ['hp', 200, 2, 44100, 0], ['bp', 3000, 5, 48000, 0], ['peak', 800, 1.2, 48000, 6], ['notch', 50, 10, 48000, 0], ['lp', 30000, 0.7, 48000, 0]];
w(`inline const char *const kBiquadType[] = {${bq.map(([t]) => `"${t}"`).join(', ')}};`);
arr('kBiquadIn', bq.flatMap(([, f, q, fs, g]) => [f, q, fs, g]));
arr('kBiquadImpulse', bq.flatMap(([t, f, q, fs, g]) => { const b = new Biquad().set(t, f, q, fs, g); return Array.from({ length: 24 }, (_, i) => b.run(i === 0 ? 1 : 0)); }));
{ const p = new OnePole(500, 48000), d = new DCBlock(10, 48000); arr('kOnePoleStep', Array.from({ length: 16 }, () => p.run(1))); arr('kDCBlockStep', Array.from({ length: 16 }, () => d.run(1))); }
{
  const d = new Delay(100), xs = [];
  for (let i = 0; i < 64; i++) { d.write(Math.sin(i * 0.37) + 0.1 * i); if (i >= 20) xs.push(d.read(1), d.read(3.25), d.read(17.9)); }
  arr('kDelayReads', xs);
}
arr('kKeyPan', [21, 36, 60, 72, 96, 108].flatMap((k) => keyPan(k)));
w();
w('// shared/impulses.js: sums and samples of the soundboard (0.4 s, and 0.3 s) and the room (2 s), at 48 and 44.1 kHz');
const irs = [['Soundboard48', soundboardIR, 48000, 0.4], ['Soundboard44', soundboardIR, 44100, 0.3], ['Room48', roomIR, 48000, 2.0], ['Room44', roomIR, 44100, 1.8]];
for (const [name, f, fs, sec] of irs) {
  const buf = f(FS_SHIM(fs), sec), ch = [0, 1].map((c) => buf.getChannelData(c));
  const at = Array.from({ length: 101 }, (_, i) => Math.floor((i * (ch[0].length - 1)) / 100));
  arr(`k${name}At`, at, 'int');
  arr(`k${name}`, ch.flatMap((x) => at.map((i) => x[i])), 'float');
  arr(`k${name}Sum`, ch.map((x) => x.reduce((a, b) => a + b, 0)));
  arr(`k${name}Length`, [ch[0].length], 'int');
  const scaled = webAudioIR(buf, fs);
  arr(`k${name}Scale`, [scaled[0][at[50]] / ch[0][at[50]] || 0]);
}
w();
w('// shared/linalg.js: eigenvalues (ascending) of fixed symmetric matrices');
const n = 6, K = Array.from({ length: n }, (_, i) => Float64Array.from({ length: n }, (_, j) => (i === j ? 2 + i : i === j - 1 || j === i - 1 ? -1 : 0.1 / (1 + i + j))));
arr('kSymK', K.flatMap((r) => [...r]));
arr('kSymLambda', symEig(K.map((r) => Float64Array.from(r)), n));
const Mflat = Float64Array.from({ length: n * n }, (_, k) => { const i = Math.floor(k / n), j = k % n; return i === j ? 1 + 0.2 * i : 0.05; });
const g = genEig(Float64Array.from(K.flatMap((r) => [...r])), Mflat, n);
arr('kGenM', Mflat);
arr('kGenLambda', g.lambda);
w();
w('// the output chain offline (tools/headless.mjs applyChain: tone, body, room, volume × trim, no limiter)');
const chain = { volume: 'volume', room: 'room', roomSeconds: 1.2, tone: 'tone', body: { param: 'body', seconds: 0.3, dry: 0.7, wet: 1.2 } };
const P = { volume: 0.8, room: 0.4, tone: 3000, body: 0.5 };
const x = [burst(24000, 7), burst(24000, 8)];
const y = applyChain({ id: '', chain }, x, P, 48000);
w('// the input: two seeded noise bursts, (r() · 2 − 1) · e^(−i/4800) · 0.3 as float, seeds 7 and 8, 24000 samples');
const pick = Array.from({ length: 200 }, (_, i) => i * 120);
arr('kChainAt', pick, 'int');
arr('kChainOut', [0, 1].flatMap((c) => pick.map((i) => y[c][i])));
arr('kChainEnergy', [0, 1].map((c) => y[c].reduce((a, v) => a + v * v, 0)));
w();
w('} // namespace js');
const text = `${out.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(FILE) || readFileSync(FILE, 'utf8') !== text) { console.error('stale: native/tests/js-vectors.h (run node tools/gen-native-vectors.mjs)'); process.exit(1); }
} else { writeFileSync(FILE, text); console.log('native/tests/js-vectors.h'); }

// sw.js — the service worker that lets Forte work offline, the iPhone's home-screen app above all.
//
// It keeps a copy of the site as it was released: every page and everything a page loads (the
// list below, written by tools/offline.mjs at each release), and serves those files from the copy
// whether or not there is a network, so a page never mixes files from two releases. The demos and
// link pictures it leaves to the network. A new release (a new list, so a new sw.js) is
// downloaded in the background, only the files that changed, each checked against its hash; it
// takes over on the way to the next page when no other tab still shows the old one
// (shared/boot.js), or once every Forte page has been closed.

const CACHE = 'forte-offline';
const BASE = new URL('./', self.location.href);
const keyOf = (path, hash) => `${BASE.href}${path}?forte=${hash}`;
const hex = (buf) => [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
const hashOf = async (buf) => hex(await crypto.subtle.digest('SHA-256', buf)).slice(0, 12);

// A file as the release has it, or an error. A CDN can still be serving the old copy for a few
// minutes after a release: then once more, past it.
async function released(path, hash) {
  for (const url of [`${BASE.href}${path}`, keyOf(path, hash)]) {
    const r = await fetch(url, { cache: 'reload' });
    if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`);
    const buf = await r.arrayBuffer();
    if (await hashOf(buf) === hash) return new Response(buf, { headers: { 'Content-Type': r.headers.get('Content-Type') || 'application/octet-stream' } });
  }
  throw new Error(`${path} isn't the released file yet`);
}

self.addEventListener('install', (e) => e.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  const have = new Set((await cache.keys()).map((r) => r.url));
  const todo = Object.entries(FILES).filter(([p, h]) => !have.has(keyOf(p, h)));
  // six at a time, as a browser fetches from one host
  await Promise.all(Array.from({ length: 6 }, async () => {
    for (let f; (f = todo.shift());) await cache.put(keyOf(...f), await released(...f));
  }));
})()));

// What this release doesn't list goes, once it is the one serving.
self.addEventListener('activate', (e) => e.waitUntil((async () => {
  for (const name of await caches.keys()) if (name !== CACHE && name.startsWith('forte-')) await caches.delete(name);
  const cache = await caches.open(CACHE), keep = new Set(Object.entries(FILES).map((f) => keyOf(...f)));
  for (const r of await cache.keys()) if (!keep.has(r.url)) await cache.delete(r);
  await self.clients.claim(); // the first visit's page, which loaded before there was a copy
})()));

// The page asks this (waiting) release to take over as it moves to another page; it does when
// that page is the only one open, since every open page's files would come from it from then on.
self.addEventListener('message', (e) => {
  if (e.data?.type !== 'forte-update') return;
  e.waitUntil((async () => {
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const ok = open.length <= 1;
    if (ok) await self.skipWaiting();
    e.ports[0]?.postMessage(ok);
  })());
});

const cached = async (path, init) => {
  const r = await (await caches.open(CACHE)).match(keyOf(path, FILES[path]));
  return r && init ? new Response(r.body, { ...init, headers: r.headers }) : r;
};

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || !req.url.startsWith(BASE.href)) return;
  const url = new URL(req.url);
  let path;
  try { path = decodeURIComponent(url.pathname.slice(BASE.pathname.length)); } catch { return; }
  if (path === '' || path.endsWith('/')) path += 'index.html';
  if (FILES[path]) {
    e.respondWith(cached(path).then((r) => r ?? fetch(req)));
  } else if (req.mode === 'navigate' && FILES[`${path}/index.html`]) {
    e.respondWith(Response.redirect(`${url.origin}${url.pathname}/${url.search}`, 301));
  } else if (req.mode === 'navigate') {
    // a page this release doesn't have: the network's answer, or offline the site's 404 page
    e.respondWith(fetch(req).catch(async () => (FILES['404.html'] && await cached('404.html', { status: 404 })) || Response.error()));
  }
  // anything else (the demos, link pictures, GitHub): the network, as without a service worker
});

